/**
 * Generates the static M3 token fallback CSS (light + dark) for the default
 * source color, using the same engine as the runtime (m3-theme.ts).
 *
 * Usage: node scripts/generate-m3-tokens.mjs "#1a6dc4" > src/styles/m3-tokens.css
 */
import {
  argbFromHex,
  hexFromArgb,
  Hct,
  SchemeTonalSpot,
} from "@material/material-color-utilities";

const sourceColor = process.argv[2] || "#1a6dc4";

const TOKEN_ROLES = [
  "primary",
  "onPrimary",
  "primaryContainer",
  "onPrimaryContainer",
  "secondary",
  "onSecondary",
  "secondaryContainer",
  "onSecondaryContainer",
  "tertiary",
  "onTertiary",
  "tertiaryContainer",
  "onTertiaryContainer",
  "error",
  "onError",
  "errorContainer",
  "onErrorContainer",
  "background",
  "onBackground",
  "outline",
  "outlineVariant",
  "shadow",
  "scrim",
  "inverseSurface",
  "inverseOnSurface",
  "inversePrimary",
  "surfaceDim",
  "surfaceBright",
  "surfaceContainerLowest",
  "surfaceContainerLow",
  "surfaceContainer",
  "surfaceContainerHigh",
  "surfaceContainerHighest",
  "onSurface",
  "onSurfaceVariant",
  "surface",
  "surfaceTint",
  "surfaceVariant",
];

const roleToProp = (role) =>
  `--md-sys-color-${role.replace(/([A-Z])/g, "-$1").toLowerCase()}`;

function buildTokenSet(scheme) {
  const tokens = {};
  for (const role of TOKEN_ROLES) {
    const value = scheme[role];
    if (typeof value === "number") {
      tokens[roleToProp(role)] = hexFromArgb(value);
    }
  }
  return tokens;
}

const hct = Hct.fromInt(argbFromHex(sourceColor));
const light = buildTokenSet(new SchemeTonalSpot(hct, false, 0.0));
const dark = buildTokenSet(new SchemeTonalSpot(hct, true, 0.0));

const out = [];
out.push(`/* ============================================================`);
out.push(` * M3 Color Tokens — static fallback for source: ${sourceColor}`);
out.push(` * Generated by scripts/generate-m3-tokens.mjs (material-theme-builder).`);
out.push(` * At runtime, src/lib/m3-theme.ts regenerates these tokens from the`);
out.push(` * user's chosen source color and injects them via <style id="m3-dynamic-theme">.`);
out.push(` * ============================================================ */`);
out.push("");
out.push(":root {");
for (const [prop, val] of Object.entries(light)) {
  out.push(`  ${prop}: ${val};`);
}
out.push("}");
out.push("");
out.push('[data-theme="dark"] {');
for (const [prop, val] of Object.entries(dark)) {
  out.push(`  ${prop}: ${val};`);
}
out.push("}");
out.push("");
process.stdout.write(out.join("\n"));
